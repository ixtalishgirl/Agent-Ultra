"""Chat store for the Agent-Ultra chat UI.

REAL, file-backed storage. One directory per chat under a base dir
(default: ~/workspace/agent-ultra/chats/). A chat holds its messages
(messages.json), its metadata (meta.json), and its browser event log
(browser_events.jsonl). A chat may link to one copy workdir (a copy
dir created by the spawner) so deleting the chat can clean up that
copy's local data too.

DELETE SAFETY (hard rule): delete() only ever removes paths that
resolve INSIDE the store base dir or inside an explicitly allowed
copies base dir. Anything else is refused with an error, never
deleted. Chat IDs are generated by this module (uuid hex), and any
ID supplied from outside is validated against a safe pattern, so a
crafted ID can never walk the path tree (no "..", no "/").

No chat content is invented here: the store starts empty, and
messages only exist once a caller appends them.
"""

import json
import re
import shutil
import time
import uuid
from pathlib import Path

_ID_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def _safe_id(chat_id):
    if not isinstance(chat_id, str) or not _ID_RE.match(chat_id):
        raise ValueError(f"invalid chat id: {chat_id!r}")
    return chat_id


def _inside(path, base):
    """True only if resolved path is inside resolved base (no escapes)."""
    try:
        return Path(path).resolve().is_relative_to(Path(base).resolve())
    except Exception:
        return False


class ChatStore:
    def __init__(self, base_dir, copies_base=None):
        self.base = Path(base_dir)
        self.base.mkdir(parents=True, exist_ok=True)
        # Copies base: where spawner copy dirs live. Delete may remove
        # a linked copy dir ONLY if it sits inside this base.
        self.copies_base = Path(copies_base) if copies_base else None

    # -- paths ------------------------------------------------------
    def chat_dir(self, chat_id):
        return self.base / _safe_id(chat_id)

    def _meta_path(self, chat_id):
        return self.chat_dir(chat_id) / "meta.json"

    def _messages_path(self, chat_id):
        return self.chat_dir(chat_id) / "messages.json"

    def _events_path(self, chat_id):
        return self.chat_dir(chat_id) / "browser_events.jsonl"

    # -- create / read ------------------------------------------------
    def create(self, title=None, copy_dir=None):
        chat_id = uuid.uuid4().hex[:12]
        d = self.chat_dir(chat_id)
        d.mkdir(parents=True, exist_ok=False)
        meta = {
            "chat_id": chat_id,
            "title": title or "New chat",
            "created": time.time(),
            "copy_dir": str(copy_dir) if copy_dir else None,
        }
        with open(self._meta_path(chat_id), "w", encoding="utf-8") as f:
            json.dump(meta, f, indent=2, sort_keys=True)
        with open(self._messages_path(chat_id), "w", encoding="utf-8") as f:
            json.dump([], f)
        return meta

    def exists(self, chat_id):
        return self._meta_path(chat_id).is_file()

    def list_chats(self):
        out = []
        for meta_path in sorted(self.base.glob("*/meta.json")):
            try:
                with open(meta_path, encoding="utf-8") as f:
                    out.append(json.load(f))
            except (OSError, json.JSONDecodeError):
                continue
        out.sort(key=lambda m: m.get("created", 0))
        return out

    def get(self, chat_id):
        if not self.exists(chat_id):
            raise KeyError(f"unknown chat: {chat_id}")
        with open(self._meta_path(chat_id), encoding="utf-8") as f:
            meta = json.load(f)
        with open(self._messages_path(chat_id), encoding="utf-8") as f:
            messages = json.load(f)
        return {"meta": meta, "messages": messages}

    def append_message(self, chat_id, role, text):
        if role not in ("user", "agent"):
            raise ValueError(f"bad role: {role!r}")
        if not isinstance(text, str) or not text.strip():
            raise ValueError("message text must be non-empty")
        data = self.get(chat_id)
        data["messages"].append(
            {"role": role, "text": text, "ts": time.time()}
        )
        with open(self._messages_path(chat_id), "w", encoding="utf-8") as f:
            json.dump(data["messages"], f, indent=2)
        return data["messages"][-1]

    # -- browser events (AG-UI-shaped, per chat) ----------------------
    def append_browser_event(self, chat_id, event):
        if not self.exists(chat_id):
            raise KeyError(f"unknown chat: {chat_id}")
        event = dict(event)
        event.setdefault("ts", time.time())
        with open(self._events_path(chat_id), "a", encoding="utf-8") as f:
            f.write(json.dumps(event, sort_keys=True) + "\n")
        return event

    def browser_events(self, chat_id):
        path = self._events_path(chat_id)
        if not path.exists():
            return []
        out = []
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    out.append(json.loads(line))
        return out

    # -- delete (scoped, real) ----------------------------------------
    def delete(self, chat_id):
        """Delete ONE chat: its dir (messages + meta + events) and, if
        linked, its copy dir — but ONLY inside the allowed bases.
        Returns what was removed. Refuses anything outside the bases.
        """
        chat_id = _safe_id(chat_id)
        if not self.exists(chat_id):
            raise KeyError(f"unknown chat: {chat_id}")
        d = self.chat_dir(chat_id)
        if not _inside(d, self.base):
            raise ValueError("refusing to delete outside the chat store")
        with open(self._meta_path(chat_id), encoding="utf-8") as f:
            meta = json.load(f)
        removed = [str(d)]
        shutil.rmtree(d)

        copy_dir = meta.get("copy_dir")
        if copy_dir:
            copy_path = Path(copy_dir)
            allowed = self.copies_base is not None and _inside(
                copy_path, self.copies_base
            )
            if not allowed:
                # Never touch a copy dir outside the allowed base.
                return {"removed": removed, "copy_dir": "REFUSED-OUTSIDE-BASE"}
            if copy_path.is_dir():
                shutil.rmtree(copy_path)
                removed.append(str(copy_path))
        return {"removed": removed, "copy_dir": copy_dir}
